
-- =====================================================
-- FINTRACK DATABASE SCHEMA
-- PostgreSQL
-- =====================================================

-- 1. USERS
CREATE TABLE users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    phone_number VARCHAR(20),
    default_account_id INTEGER,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- 2. ACCOUNTS
CREATE TABLE accounts (
    account_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    account_name VARCHAR(100) NOT NULL,
    account_type VARCHAR(20) NOT NULL
        CHECK (account_type IN ('Bank', 'Cash', 'Savings', 'Credit')),
    balance NUMERIC(12,2) NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_account_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
        ON DELETE CASCADE,

    CONSTRAINT chk_account_balance
        CHECK (balance >= 0),

    CONSTRAINT uq_account_owner
        UNIQUE (account_id, user_id)
);


-- 3. DEFAULT ACCOUNT RELATIONSHIP
-- Added after accounts to resolve the circular relationship.
ALTER TABLE users
ADD CONSTRAINT fk_user_default_account
FOREIGN KEY (default_account_id, user_id)
REFERENCES accounts(account_id, user_id)
ON DELETE SET NULL (default_account_id)
DEFERRABLE INITIALLY DEFERRED;


-- 4. CATEGORIES
-- A NULL user_id represents a shared system category.
CREATE TABLE categories (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER,
    category_name VARCHAR(100) NOT NULL,
    category_type VARCHAR(20) NOT NULL
        CHECK (category_type IN ('Income', 'Expense')),
    description TEXT,

    CONSTRAINT fk_category_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
        ON DELETE CASCADE
);


-- 5. TRANSACTIONS
CREATE TABLE transactions (
    transaction_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    account_id INTEGER NOT NULL,
    category_id INTEGER NOT NULL,
    amount NUMERIC(12,2) NOT NULL,
    transaction_type VARCHAR(20) NOT NULL
        CHECK (transaction_type IN ('Income', 'Expense')),
    transaction_date DATE NOT NULL DEFAULT CURRENT_DATE,
    description TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_transaction_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_transaction_account_owner
        FOREIGN KEY (account_id, user_id)
        REFERENCES accounts(account_id, user_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_transaction_category
        FOREIGN KEY (category_id)
        REFERENCES categories(category_id),

    CONSTRAINT chk_transaction_amount
        CHECK (amount > 0)
);


-- 6. BUDGETS
CREATE TABLE budgets (
    budget_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    budget_name VARCHAR(100) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_budget_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
        ON DELETE CASCADE,

    CONSTRAINT chk_budget_dates
        CHECK (end_date >= start_date)
);


-- 7. BUDGET_CATEGORY
-- Junction table for the many-to-many Budget-Category relationship.
CREATE TABLE budget_category (
    budget_id INTEGER NOT NULL,
    category_id INTEGER NOT NULL,
    allocated_amount NUMERIC(12,2) NOT NULL,

    CONSTRAINT pk_budget_category
        PRIMARY KEY (budget_id, category_id),

    CONSTRAINT fk_budget_category_budget
        FOREIGN KEY (budget_id)
        REFERENCES budgets(budget_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_budget_category_category
        FOREIGN KEY (category_id)
        REFERENCES categories(category_id)
        ON DELETE CASCADE,

    CONSTRAINT chk_allocated_amount
        CHECK (allocated_amount >= 0)
);


-- 8. SAVINGS GOALS
CREATE TABLE savings_goals (
    goal_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    account_id INTEGER,
    goal_name VARCHAR(100) NOT NULL,
    target_amount NUMERIC(12,2) NOT NULL,
    saved_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    target_date DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'Active',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_goal_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_goal_account_owner
        FOREIGN KEY (account_id, user_id)
        REFERENCES accounts(account_id, user_id)
        ON DELETE SET NULL (account_id),

    CONSTRAINT chk_goal_target
        CHECK (target_amount > 0),

    CONSTRAINT chk_goal_saved
        CHECK (saved_amount >= 0),

    CONSTRAINT chk_goal_status
        CHECK (status IN ('Active', 'Completed', 'Cancelled'))
);


-- =====================================================
-- INDEXES
-- =====================================================
CREATE INDEX idx_accounts_user
    ON accounts(user_id);

CREATE INDEX idx_transactions_user_date
    ON transactions(user_id, transaction_date);

CREATE INDEX idx_transactions_account
    ON transactions(account_id);

CREATE INDEX idx_transactions_category
    ON transactions(category_id);

CREATE INDEX idx_categories_user
    ON categories(user_id);

CREATE INDEX idx_budgets_user
    ON budgets(user_id);

CREATE INDEX idx_savings_goals_user
    ON savings_goals(user_id);
